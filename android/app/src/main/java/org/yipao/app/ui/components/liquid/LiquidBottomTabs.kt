// 背景模糊从库默认的 8dp 收到 3dp。糊太狠背景就成了一团色，折射弯出来的那点
// 纹理全被抹平，玻璃反而不像玻璃；但一点都不糊也不行——试过纯折射+40% 底色，
// 功能页滚动时底下卡片的字直接透上来，跟 tab 标签叠成一片认不出。3dp 是
// 「还看得见背景的形、但底下的字已经读不出来」这条线。
